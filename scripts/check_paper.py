"""
scripts/check_paper.py

Assert that the numbers in `paper/draft.md` still match `results/runs/`.

    python -m scripts.check_paper

WHY THIS EXISTS
---------------
Tables in the draft are generated by `scripts/make_tables.py` and are safe. Numbers in the
*prose* are not: they are typed, and a paper's prose outlives the run that produced it.
This project has already been caught twice by exactly that -- a summary paragraph quoting a
result from before the head-width fix, and a comparison CSV silently narrowed by a re-run
with fewer `--datasets`, which turned a 7-of-8 result into a 1-of-8 one until it was noticed.

So every headline number in the draft is restated here as an assertion against the archive
that produced it. The check reads the draft, finds the claim, recomputes the quantity, and
fails if they disagree. It is the same contract `scripts/check_configs.py` has with the
trainers' defaults.

A claim that becomes wrong is a failure, and a claim that disappears from the draft is also
a failure -- silently dropping an inconvenient number should not pass a check named this.

Exit code is non-zero on any mismatch, so it belongs in the same gate as check_configs.
"""

import os
import re
import sys

import numpy as np
import pandas as pd

DRAFT = os.path.join("paper", "draft.md")
MET = os.path.join("results", "metrics")


def compare(a, b):
    p = os.path.join(MET, f"view_compare_{a}_vs_{b}.csv")
    return pd.read_csv(p) if os.path.exists(p) else None


def conformal(name="absolute"):
    p = os.path.join(MET, f"conformal_alpha0.1_{name}.csv")
    return pd.read_csv(p) if os.path.exists(p) else None


# Each check returns (label, value_in_archive, tolerance). The literal expected value is
# parsed out of the draft so the two cannot drift apart silently.
def checks(draft):
    out = []

    def claim(label, pattern, actual, tol=5e-4, scale=1.0):
        m = re.search(pattern, draft)
        if m is None:
            out.append((label, None, actual, tol, "CLAIM MISSING FROM DRAFT"))
        else:
            out.append((label, float(m.group(1)) * scale, actual, tol, None))

    d = compare("fuse_proposed", "gin_ref")
    if d is not None:
        claim("proposed vs gin_ref: datasets favoured",
              r"\*\*`proposed` vs baseline `gin_ref`\*\* \| \*\*(\d)/8\*\*",
              float(d.across_wins.iloc[0]), 0)
        claim("proposed vs gin_ref: sign p",
              r"\*\*`proposed` vs baseline `gin_ref`\*\* \| \*\*\d/8\*\* \| \*\*([\d.]+)\*\*",
              float(d.across_p_sign.iloc[0]), 1e-3)

    d = compare("fuse_proposed", "desc")
    if d is not None:
        claim("proposed vs desc: datasets favoured",
              r"\*\*`proposed` vs `desc`\*\* \| (\d)/8", float(d.across_wins.iloc[0]), 0)

    d = compare("fuse_gated_nograph", "fuse_gated")
    if d is not None:
        claim("leave-one-view-out: sign-test p",
              r"no across-dataset difference: sign test p = ([\d.]+)",
              float(d.across_p_sign.iloc[0]), 5e-3)
        claim("leave-one-view-out: Wilcoxon-dz p",
              r"Wilcoxon on \*dz\* p = ([\d.]+)\)",
              float(d.across_p_wilcoxon_dz.iloc[0]), 5e-3)

    # The set-size diagnostic of section 6.2, and the abstract's restatement of it. These
    # went stale twice -- once when AttentiveFP joined and once when Chemprop did -- because
    # the counts are prose, not a generated table, and nothing recomputed them. Every number
    # in the split is now derived from the archive.
    c = conformal("absolute")
    if c is not None:
        t21 = c[c.dataset == "tox21"]
        small = t21[t21.mean_set_size <= 1.05]
        big = t21[t21.mean_set_size > 1.05]
        flat = " ".join(draft.split())

        for label, group, pat in (
            ("set-size<=1.05 model count", small,
             r"\| mean set size . 1\.05 \| (\d+) \(random forest"),
            ("set-size>1.05 model count", big,
             r"\| mean set size > 1\.05 \| (\d+) \(everything else\)"),
        ):
            m = re.search(pat, draft)
            out.append((label, None if m is None else float(m.group(1)),
                        float(len(group)), 0,
                        None if m is not None else "ROW MISSING FROM DRAFT"))

        # Both the abstract and 6.2 quote the two coverage ranges; assert every endpoint.
        for label, value in (
            ("failing group: min actives", 100 * float(small.coverage_pos.min())),
            ("failing group: max actives", 100 * float(small.coverage_pos.max())),
            ("covering group: min actives", 100 * float(big.coverage_pos.min())),
            ("covering group: max actives", 100 * float(big.coverage_pos.max())),
        ):
            out.append((label, value if f"{value:.1f}" in flat else None, value, 0.05,
                        None if f"{value:.1f}" in flat
                        else f"{value:.1f}% not quoted anywhere in the draft"))

        # The total, quoted as a word in both places. Searched in the flattened text: the
        # draft is hard-wrapped and the abstract breaks this very phrase across a line.
        WORDS = {"thirteen": 13, "fourteen": 14, "fifteen": 15, "sixteen": 16}
        for pat, label in ((r"from three model types to (\w+)", "abstract model count"),
                           (r"one mechanism: (\w+) models including", "6.2 model count")):
            m = re.search(pat, flat)
            if m is None:
                out.append((label, None, float(len(t21)), 0, "CLAIM MISSING FROM DRAFT"))
            else:
                stated = WORDS.get(m.group(1).lower())
                out.append((label, None if stated is None else float(stated),
                            float(len(t21)), 0,
                            None if stated is not None
                            else f"could not read '{m.group(1)}' as a number"))

        t = t21
        rf = t[t.tag == "rf"]
        if len(rf):
            claim("Tox21 rf actives coverage",
                  r"\| Random forest \| [\d.]+% \| \*\*([\d.]+)%\*\*",
                  100 * float(rf.coverage_pos.iloc[0]), 0.05)
        de = t[t.tag == "desc"]
        if len(de):
            claim("Tox21 desc actives coverage",
                  r"\| `desc` \| [\d.]+% \| ([\d.]+)% \|",
                  100 * float(de.coverage_pos.iloc[0]), 0.05)

    d = compare("attentivefp", "gin_ref_gpu")
    if d is not None:
        claim("AttentiveFP vs baseline GIN: datasets favoured",
              r"\| AttentiveFP vs `gin_ref` \(baseline\)\* \| (\d)/8",
              float(d.across_wins.iloc[0]), 0)
    d = compare("fuse_proposed_gpu", "attentivefp")
    if d is not None:
        claim("proposed vs AttentiveFP: datasets favoured",
              r"\| \*\*`proposed` vs AttentiveFP\*\* \| \*\*(\d)/8\*\*",
              float(d.across_wins.iloc[0]), 0)
        claim("proposed vs AttentiveFP: sign p",
              r"\| \*\*`proposed` vs AttentiveFP\*\* \| \*\*\d/8\*\* \| ([\d.]+)",
              float(d.across_p_sign.iloc[0]), 5e-3)

    # Encoder sizes: the draft quotes each figure at least once, so a changed architecture
    # cannot leave a stale parameter count in the prose. Newlines are normalised first
    # because the draft is hard-wrapped and a count can straddle a line break.
    from src.models.encoders.graph import build_graph_encoder

    flat = " ".join(draft.split())
    for enc, label in (("attentivefp", "AttentiveFP params"),
                       ("gine", "GINE params"),
                       ("gin", "inherited GIN params")):
        n = sum(q.numel() for q in build_graph_encoder(enc, in_dim=34, hidden=256).parameters())
        quoted = f"{n:,}" in flat
        out.append((label, float(n) if quoted else None, float(n), 0,
                    None if quoted else f"{n:,} not quoted anywhere in the draft"))

    # Section 5.6 mechanism attribution. All three settings of the headline row are checked,
    # so a single re-run cannot quietly flip one, and the end-to-end column is pinned by
    # position so the three-column table cannot be silently reordered.
    for a, b, pat, label in (
        ("fuse_bilinear", "fuse_concat",
         r"\| `bilinear` vs `concat` \| 7/8, \*\*p = ([\d.]+)\*\*", "cached bilinear vs concat dz"),
        ("fuse_bilinear_gpu", "fuse_concat_gpu",
         r"\| `bilinear` vs `concat` \| 7/8, \*\*p = [\d.]+\*\* \| 8/8, \*\*p = ([\d.]+)\*\*",
         "cached-T4 bilinear vs concat dz"),
        ("fuse_proposed_e2e", "fuse_xattn_e2e",
         r"\| \*\*`proposed` vs `xattn`\*\* \| 6/8, p = [\d.]+ \| 7/8, p = [\d.]+ "
         r"\| 7/8, \*\*p = ([\d.]+)\*\*",
         "e2e proposed vs xattn dz"),
    ):
        d = compare(a, b)
        if d is not None:
            claim(label, pat, float(d.across_p_wilcoxon_dz.iloc[0]), 5e-4)

    # Section 5.6, the rank sweep. The whole point of this sub-section is that the p-value
    # moves with the rank while the effect does not, so every cell of the rank table is
    # asserted -- a claim this uncomfortable is exactly the one that must not be allowed to
    # drift, in either direction.
    RANK_ROW = {
        16: r"\| 16 \| 24,768 \| (\d)/8 \| ([\d.]+) \| ([\d.]+) \| ([\d.]+) \|",
        32: r"\| 32 \| 49,536 \| (\d)/8 \| ([\d.]+) \| ([\d.]+) \| ([\d.]+) \|",
        64: r"\| \*\*64\*\* \| \*\*99,072\*\* \| \*\*(\d)/8\*\* \| \*\*([\d.]+)\*\* "
            r"\| \*\*([\d.]+)\*\* \| \*\*([\d.]+)\*\* \|",
        128: r"\| 128 \| 198,144 \| (\d)/8 \| ([\d.]+) \| ([\d.]+) \| ([\d.]+) \|",
    }
    for r, pat in RANK_ROW.items():
        tag = "fuse_bilinear_gpu" if r == 64 else f"fuse_bilinear_r{r}_gpu"
        d = compare(tag, "fuse_concat_gpu")
        m = re.search(pat, draft)
        if d is None:
            continue
        if m is None:
            out.append((f"rank {r} row", None, 0.0, 0, "RANK ROW MISSING FROM DRAFT"))
            continue
        for i, (col, tol) in enumerate((("across_wins", 0), ("across_p_sign", 5e-4),
                                        ("across_p_wilcoxon_dz", 5e-4),
                                        ("across_p_wilcoxon_raw", 5e-4))):
            out.append((f"rank {r}: {col}", float(m.group(i + 1)),
                        float(d[col].iloc[0]), tol, None))

    # Two DIFFERENT comparisons that a careless reading conflates, so both are pinned:
    # the inertness claim is r128 against r16 (the extremes), while the Gelman-Stern
    # sentence is r64 against r16 -- the pair whose two arms disagree about significance
    # against `concat`. Using one archive for both would have silently asserted the wrong
    # number against the right sentence.
    d = compare("fuse_bilinear_r128_gpu", "fuse_bilinear_r16_gpu")
    if d is not None:
        claim("rank extremes indistinguishable (r128 vs r16)",
              r"eight times apart . differ at p = (\d\.\d+)",
              float(d.across_p_wilcoxon_dz.iloc[0]), 5e-4)
    d = compare("fuse_bilinear_r16_gpu", "fuse_bilinear_gpu")
    if d is not None:
        claim("Gelman-Stern pair (r64 vs r16) not significant",
              r"is \*also\* not significant, at p = (\d\.\d+)",
              float(d.across_p_wilcoxon_dz.iloc[0]), 5e-4)

    # Fusion-block parameter counts per rank, recomputed from the model definition so the
    # table cannot quote a size the code no longer builds.
    from src.models.fusion import build_fusion as _bf
    for r in (16, 32, 64, 128):
        n = sum(p.numel() for p in _bf("bilinear", n_views=3, d=256, rank=r).parameters())
        if f"{n:,}" not in " ".join(draft.split()):
            out.append((f"rank {r} parameter count", None, float(n), 0,
                        f"{n:,} not quoted in the draft"))

    # Section 8: the duplicate-label ceiling. Checked against the audit's own output rather
    # than against numbers typed into the limitations list, and the no-leakage claim is
    # asserted as a number (zero) rather than left as prose -- it is the load-bearing half.
    dup_path = os.path.join(MET, "duplicate_audit.csv")
    if os.path.exists(dup_path):
        dup = pd.read_csv(dup_path).set_index("dataset")
        for ds, label in (("bbbp", "BBBP"), ("clintox", "ClinTox"), ("esol", "ESOL")):
            if ds not in dup.index:
                continue
            row = dup.loc[ds]
            pat = (rf"\| {label} \| ([\d,]+) \| ([\d,]+) \| (\d+) \| (\d+) \|")
            m = re.search(pat, draft)
            if m is None:
                out.append((f"duplicate audit: {label}", None, 0.0, 0,
                            "ROW MISSING FROM DRAFT"))
                continue
            for i, col in enumerate(("rows", "unique_molecules", "duplicate_groups",
                                     "conflicting_groups")):
                out.append((f"duplicates {label}: {col}",
                            float(m.group(i + 1).replace(",", "")),
                            float(row[col]), 0, None))
        # The load-bearing half of the limitation: duplicates exist but never cross a split,
        # so they are a noise ceiling and not leakage. Asserted as a number rather than left
        # as prose, because it is the half a reader would most want verified.
        out.append(("duplicates: no group spans a split", 0.0,
                    float(dup.groups_spanning_splits.sum()), 0, None))

        # "The other five datasets have no duplicates at all" -- spelled number in the prose,
        # counted from the audit.
        WORDS = {"three": 3, "four": 4, "five": 5, "six": 6}
        clean = float((dup.duplicate_groups == 0).sum())
        m = re.search(r"The other (\w+) datasets have no duplicates at all", draft)
        if m is None:
            out.append(("datasets with no duplicates", None, clean, 0,
                        "CLAIM MISSING FROM DRAFT"))
        else:
            stated = WORDS.get(m.group(1).lower())
            out.append(("datasets with no duplicates",
                        None if stated is None else float(stated), clean, 0,
                        None if stated is not None
                        else f"could not read '{m.group(1)}' as a number"))

    e = os.path.join(MET, "ece_multiseed.csv")
    if os.path.exists(e):
        ec = pd.read_csv(e)
        # The hurts count is not hard-coded into this pattern: it was 0 until Chemprop
        # joined, and a check that breaks when an honest number changes trains people to
        # edit the check instead of the claim.
        claim("calibration: pairs where it helps",
              r"decisively helps on (\d+), hurts on \d+", float(ec.helps.sum()), 0)
        claim("calibration: pairs where it hurts",
              r"decisively helps on \d+, hurts on (\d+)", float(ec.hurts.sum()), 0)
        claim("calibration: total pairs",
              r"Across (\d+) \(model, dataset\) pairs", float(len(ec)), 0)

    # Parameter counts, recomputed from the model definitions rather than read from a file.
    from src.models.fusion import build_fusion
    for mode, pattern, label in (
        ("gated", r"\| `gated` \| per-molecule softmax over views \| \*\*([\d,]+)\*\* \|",
         "gate parameters"),
        ("proposed", r"\| `proposed` \| xattn → bilinear → gate \| \*\*([\d,]+)\*\* \|",
         "proposed fusion parameters"),
    ):
        n = sum(p.numel() for p in build_fusion(mode, n_views=3, d=256).parameters())
        m = re.search(pattern, draft)
        if m is None:
            out.append((label, None, float(n), 0, "CLAIM MISSING FROM DRAFT"))
        else:
            out.append((label, float(m.group(1).replace(",", "")), float(n), 0, None))

    # The canonical-vs-seeded split gap. Quoted in three places (abstract, 3.2, 5.6) and
    # already drifted once -- 5.6 said 0.18 while 3.2 said 0.22 -- so all three are pinned
    # to the archive that produces them rather than to each other.
    def _bbbp_gap():
        runs = os.path.join("results", "runs")
        dc_path = os.path.join(runs, "deepchem", "metrics", "bbbp_gnn_test.csv")
        if not os.path.exists(dc_path):
            return None
        dc = float(pd.read_csv(dc_path).iloc[0]["auc"])
        seeds = []
        for s in (f"seed{i}" for i in range(5)):
            q = os.path.join(runs, s, "metrics", "bbbp_gnn_test.csv")
            if os.path.exists(q):
                seeds.append(float(pd.read_csv(q).iloc[0]["auc"]))
        return (dc, float(np.mean(seeds))) if len(seeds) == 5 else None

    gap = _bbbp_gap()
    if gap is not None:
        dc, seeded = gap
        claim("split gap: canonical BBBP graph AUC", r"BBBP, graph baseline: ([\d.]+) canonical",
              dc, 5e-5)
        claim("split gap: seeded BBBP graph AUC",
              r"BBBP, graph baseline: [\d.]+ canonical against ([\d.]+)", seeded, 5e-5)
        for pat, label in (
            (r"differ by \*\*up to ([\d.]+) AUC on the same model", "3.2 split gap"),
            (r"a single scaffold split producing a ([\d.]+) AUC swing", "5.6 split gap"),
        ):
            claim(label, pat, abs(seeded - dc), 5e-3)

    # Section 5.3's pipeline comparison. This table exists because `gin_ref` is one encoder
    # and the draft previously read as though beating it meant beating the whole earlier
    # system. Every row is asserted, and the `hybrid` row especially -- it is the one that
    # makes the claim honest, so it is the one nobody should be able to drop quietly.
    for b, label in (("rf", "rf"), ("gnn", "gnn"), ("trf", "trf"), ("hybrid", "hybrid")):
        d = compare("fuse_proposed", b)
        if d is None:
            continue
        bold = r"\*\*" if b == "hybrid" else ""
        pat = (rf"\| {bold}`proposed` vs `{b}`{bold} \| \*\*(\d)\+ / 0−\*\* \| (\d)/5 \| "
               rf"([\d.]+) \| ([\d.]+) \| ([\d.]+) \|")
        m = re.search(pat, draft)
        if m is None:
            out.append((f"5.3 pipeline row: {label}", None, 0.0, 0, "ROW MISSING FROM DRAFT"))
            continue
        # Counted from the per-dataset Holm verdicts, not read from a summary column --
        # there isn't one, and asserting the draft's own number against itself would be a
        # check that can never fail.
        out.append((f"5.3 {label}: improves after Holm", float(m.group(1)),
                    float((d.verdict_holm == "improves").sum()), 0, None))
        out.append((f"5.3 {label}: favoured", float(m.group(2)),
                    float(d.across_wins.iloc[0]), 0, None))
        out.append((f"5.3 {label}: sign p", float(m.group(3)),
                    float(d.across_p_sign.iloc[0]), 5e-4, None))
        out.append((f"5.3 {label}: dz p", float(m.group(4)),
                    float(d.across_p_wilcoxon_dz.iloc[0]), 5e-4, None))
        out.append((f"5.3 {label}: raw p", float(m.group(5)),
                    float(d.across_p_wilcoxon_raw.iloc[0]), 5e-4, None))

    # Section 6.6's distance table, now a fifteen-model average rather than one model's.
    # Every cell is asserted: it is a five-row table of prose numbers, which is exactly the
    # shape that has gone stale three times in this project already.
    bd_path = os.path.join(MET, "conformal_alpha0.1_bydistance.csv")
    if os.path.exists(bd_path):
        bd = pd.read_csv(bd_path)
        bd = bd[bd.dataset == "tox21"]
        if len(bd):
            g = bd.groupby("band")[["coverage", "coverage_pos", "n_band"]].mean()
            for band in g.index:
                r = g.loc[band]
                lo, hi = band.split("-")
                pat = (rf"\| {lo}[–-]{hi}[^|]*\| (\d+) \| ([\d.]+)% \| \*?\*?([\d.]+)%")
                m = re.search(pat, draft)
                if m is None:
                    out.append((f"6.6 band {band}", None, 0.0, 0, "ROW MISSING FROM DRAFT"))
                    continue
                out.append((f"6.6 {band}: n", float(m.group(1)), float(r.n_band), 0.6, None))
                out.append((f"6.6 {band}: overall", float(m.group(2)),
                            100 * float(r.coverage), 0.05, None))
                out.append((f"6.6 {band}: actives", float(m.group(3)),
                            100 * float(r.coverage_pos), 0.05, None))

    # Section 3.2's asymmetry claim: the canonical split is systematically harder. Recomputed
    # from the archives rather than trusted, because it is a new claim and the three numbers
    # in it (33 of 37, median, 30 beyond the MDE) move together if any archive changes.
    def _canonical_vs_seeded():
        from src.data.materialize import dataset_names
        from src.eval.metrics import is_classification as _is_cls
        runs = os.path.join("results", "runs")
        tags = ["rf", "gnn", "trf", "hybrid", "gin_ref", "desc", "gine", "fuse_gated",
                "fuse_proposed"]
        dc, sd = [], []
        for tag in tags:
            for ds in dataset_names():
                if not _is_cls(ds):
                    continue
                p = os.path.join(runs, "deepchem", "metrics", f"{ds}_{tag}_test.csv")
                if not os.path.exists(p):
                    continue
                vals = []
                for s in (f"seed{i}" for i in range(5)):
                    q = os.path.join(runs, s, "metrics", f"{ds}_{tag}_test.csv")
                    if os.path.exists(q):
                        vals.append(float(pd.read_csv(q).iloc[0]["auc"]))
                if len(vals) == 5:
                    dc.append(float(pd.read_csv(p).iloc[0]["auc"]))
                    sd.append(float(np.mean(vals)))
        return np.asarray(dc), np.asarray(sd)

    dc_a, sd_a = _canonical_vs_seeded()
    if dc_a.size:
        diff = sd_a - dc_a
        claim("3.2 asymmetry: n pairs", r"the\s+\*\*(\d+)\*\* \(model, dataset\) pairs",
              float(dc_a.size), 0)
        claim("3.2 asymmetry: seeded higher",
              r"the seeded mean is higher than the canonical split on \*\*(\d+)\*\*",
              float((diff > 0).sum()), 0)
        claim("3.2 asymmetry: median difference",
              r"median difference of\s+\*\*\+([\d.]+) AUC\*\*", float(np.median(diff)), 5e-4)
        claim("3.2 asymmetry: beyond MDE",
              r"\*\*(\d+)\*\* of 37 pairs separated by more than our minimum detectable",
              float((np.abs(diff) > 0.02).sum()), 0)

    # Derived quantities the draft asserts about the protocol itself.
    claim("family-wise error rate for 8 tests at 0.05",
          r"produce at least one false positive (\d+)% of the time",
          100 * (1 - 0.95 ** 8), 0.5)
    claim("across-dataset sign-test floor",
          r"signed-rank floor at p = ([\d.]+)", 2 / 2 ** 8, 5e-5)

    # Descriptor physics.
    z = np.load(os.path.join("data", "pool", "freesolv_desc.npz"))
    names = [str(n) for n in z["names"]]
    y = np.load(os.path.join("data", "pool", "freesolv_ecfp.npz"))["y_raw"].ravel()
    r = float(np.corrcoef(z["X"][:, names.index("TPSA")], y)[0, 1])
    claim("TPSA vs hydration free energy", r"at r = −([\d.]+)", abs(r), 5e-4)

    return out


def main():
    if not os.path.exists(DRAFT):
        raise SystemExit(f"{DRAFT} not found.")
    draft = open(DRAFT, encoding="utf-8").read()

    rows = checks(draft)
    bad = []
    for label, stated, actual, tol, err in rows:
        if err:
            bad.append(f"  {label:44s} {err}")
        elif abs(stated - actual) > tol:
            bad.append(f"  {label:44s} draft={stated!r}  archive={actual!r}")

    if bad:
        print(f"{len(bad)} of {len(rows)} paper claims FAILED:\n")
        print("\n".join(bad))
        print("\nEither the draft is stale (update it) or a result moved (say so in "
              "the project log). Do not adjust the tolerance to make this pass.")
        sys.exit(1)

    # The draft's own appendix quotes the assertion count. Assert that too, so the one
    # number describing this checker cannot drift away from what it actually checks.
    m = re.search(r"check_paper\s+# (\d+) assertions", draft)
    if m and int(m.group(1)) != len(rows):
        print(f"Appendix A says {m.group(1)} assertions; this run has {len(rows)}.")
        print("Update the appendix.")
        sys.exit(1)

    print(f"All {len(rows)} headline claims in {DRAFT} match the archives.")


if __name__ == "__main__":
    main()
