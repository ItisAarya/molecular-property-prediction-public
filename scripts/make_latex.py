r"""
scripts/make_latex.py

Convert `paper/draft.md` into an Overleaf-ready LaTeX project.

    python -m scripts.make_latex

Writes `paper/latex/main.tex`, copies the figures and `references.bib` beside it, and packs all
of it into `paper/overleaf_project.zip`.

WHY A CONVERTER AND NOT A HAND-WRITTEN .tex
-------------------------------------------
The Markdown draft is the source of truth: `scripts/check_paper.py` asserts its prose against
the archives, and a hand-maintained LaTeX copy would drift from it within a day. So the LaTeX
is generated, and regenerating it after every edit to the draft costs one command.

WHAT THE DRAFT MAY USE, AND WHAT EACH BECOMES
---------------------------------------------
    ## Abstract                         \begin{abstract} ... \end{abstract}
    ## 3. Title / ### 3.2 Title         \section{Title}\label{sec:3} / \subsection ... \label{sec:3.2}
    #### Title                          \subsubsection*{Title}
    ## Declarations (no number)         \section*{Declarations}
    ## Appendix A. Title                \appendix \section{Title}\label{sec:A}
    Section 3.2 / Sections 3.2 and 5   Section~\ref{sec:3.2} (and each number in a list)
    [@key] / [@key1; @key2]            \cite{key} / \cite{key1,key2}
    **Table N.** caption, then a table  table float, caption above, \label{tab:N}
    ![..](figures/x.png), then          figure float, caption below, \label{fig:N}
      **Figure N.** caption
    Table N / Figure N in the text      Table~\ref{tab:N} / Figure~\ref{fig:N}

Every citation key must exist in `references.bib`, and every bibliography entry must be cited,
or the build stops. Floats are numbered by LaTeX in order of appearance, so the build also stops
if the draft's own Table/Figure numbers are not in order of appearance -- otherwise the numbers a
reader sees in the Markdown and in the PDF would differ.
"""

import io
import os
import re
import shutil
import unicodedata
import zipfile

SRC = os.path.join("paper", "draft.md")
OUT_DIR = os.path.join("paper", "latex")
FIG_SRC = os.path.join("paper", "figures")
ZIP_OUT = os.path.join("paper", "overleaf_project.zip")
BIB = os.path.join("paper", "references.bib")

PREAMBLE = r"""% Generated by scripts/make_latex.py from paper/draft.md -- do not edit by hand.
% Regenerate with:  python -m scripts.make_latex
\documentclass[11pt,a4paper]{article}

\usepackage[utf8]{inputenc}
\usepackage[T1]{fontenc}
\usepackage{lmodern}
\usepackage[margin=2.5cm]{geometry}
\usepackage{graphicx}
\usepackage{booktabs}
\usepackage{array}
\usepackage{amsmath,amssymb}
\usepackage{enumitem}
\usepackage{microtype}
\usepackage{float}
\usepackage[skip=6pt]{caption}
\usepackage[hidelinks]{hyperref}

\newcommand{\code}[1]{\texttt{\small #1}}

\setlist{itemsep=2pt,parsep=0pt,topsep=4pt}
\renewcommand{\arraystretch}{1.15}

\title{@@TITLE@@}

% Single author. Venue-neutral on purpose: no \affiliation or \orcid macro is used, because
% those are defined by publisher classes and not by `article`. Swap this block for the
% venue's own once a template is chosen.
\author{%
  Aarya Sharma \\[2pt]
  \normalsize Department of Artificial Intelligence and Machine Learning \\
  \normalsize Universal College of Engineering, University of Mumbai, India \\[2pt]
  \normalsize \href{mailto:aarya007india@gmail.com}{aarya007india@gmail.com} \\
  \normalsize ORCID: \href{https://orcid.org/0009-0003-4765-9849}{0009-0003-4765-9849}%
}
\date{}

\begin{document}
\maketitle
"""

SPECIALS = {
    "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
    "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}
UNICODE = {
    "—": "---", "–": "--", "×": r"$\times$", "±": r"$\pm$", "≤": r"$\leq$",
    "≥": r"$\geq$", "≈": r"$\approx$", "→": r"$\rightarrow$", "α": r"$\alpha$",
    "ρ": r"$\rho$", "§": r"\S", "‘": "`", "’": "'", "“": "``", "”": "''", "…": r"\dots{}",
    "⊕": r"$\oplus$", "·": r"$\cdot$", "≡": r"$\equiv$", "Δ": r"$\Delta$", "σ": r"$\sigma$",
    "β": r"$\beta$", "κ": r"$\kappa$", "λ": r"$\lambda$",
    # inputenc's utf8 option defines the Latin-1 range and little beyond it, so each of these
    # is a "Unicode character not set up for use with LaTeX" error rather than a bad glyph.
    "−": "$-$", "′": "$'$", "∈": r"$\in$", "≠": r"$\neq$", "√": r"$\surd$",
    # Dotless i (as in Eryılmaz) is missing from the T1 Latin Modern font under XeTeX, so it is
    # spelled with the LaTeX command, which every engine renders.
    "ı": r"{\i}", "š": r"{\v{s}}",
}

SUPERSCRIPTS = {
    "⁰": "0", "¹": "1", "²": "2", "³": "3", "⁴": "4", "⁵": "5",
    "⁶": "6", "⁷": "7", "⁸": "8", "⁹": "9", "⁺": "+", "⁻": "-",
}
SUPER_RUN = re.compile("[" + "".join(SUPERSCRIPTS) + "]+")
SUBSCRIPTS = {"₀": "0", "₁": "1", "₂": "2", "₃": "3", "₄": "4", "₅": "5", "₆": "6", "₇": "7",
              "₈": "8", "₉": "9"}
SUB_RUN = re.compile("[" + "".join(SUBSCRIPTS) + "]+")

CITE_RE = re.compile(r"\[(@[\w:-]+(?:\s*;\s*@[\w:-]+)*)\]")
_SEC_ID = r"(?:[A-Z](?![A-Za-z])|\d+(?:\.\d+)*)"
SECTION_REF = re.compile(r"\bSections?\s+(" + _SEC_ID + r"(?:(?:,\s*|,?\s+and\s+|\s*[–-]\s*)"
                         + _SEC_ID + r")*)")
FLOAT_REF = re.compile(r"\b(Table|Figure)s?\s+(\d+)")

USED_KEYS = []


def superscripts(s):
    s = SUPER_RUN.sub(lambda m: r"\textsuperscript{" + "".join(SUPERSCRIPTS[c] for c in m.group(0))
                      + "}", s)
    return SUB_RUN.sub(lambda m: r"\textsubscript{" + "".join(SUBSCRIPTS[c] for c in m.group(0))
                       + "}", s)


def bib_keys(path):
    return re.findall(r"^@\w+\{([^,]+),", io.open(path, encoding="utf-8").read(), flags=re.M)


def cite(s):
    def repl(m):
        keys = [k.strip().lstrip("@") for k in m.group(1).split(";")]
        for k in keys:
            if k not in USED_KEYS:
                USED_KEYS.append(k)
        return "\\cite{" + ",".join(keys) + "}"
    s = re.sub(r" (?=" + CITE_RE.pattern + ")", "~", s)
    return CITE_RE.sub(repl, s)


def section_refs(s):
    def one(num):
        return f"\\ref{{sec:{num}}}"

    def repl(m):
        word = "Sections" if m.group(0).startswith("Sections") else "Section"
        body = re.sub(_SEC_ID, lambda n: one(n.group(0)), m.group(1))
        return f"{word}~{body}"
    return SECTION_REF.sub(repl, s)


def float_refs(s):
    def repl(m):
        kind = "tab" if m.group(1) == "Table" else "fig"
        return m.group(0).split()[0] + "~\\ref{" + kind + ":" + m.group(2) + "}"
    return FLOAT_REF.sub(repl, s)


PIPE_MARK = "@@PIPE@@"
STAR_MARK = "@@STAR@@"


def esc(text):
    """Escape LaTeX specials outside inline code, map unicode, then emphasis, links, refs, cites."""
    text = text.replace("\\|", PIPE_MARK).replace("\\*", STAR_MARK)
    out = []
    for part in re.split(r"(`[^`]*`)", text):
        if part.startswith("`") and part.endswith("`") and len(part) > 1:
            inner = part[1:-1]
            for k, v in SPECIALS.items():
                inner = inner.replace(k, v)
            out.append("\\code{" + inner + "}")
            continue
        for k, v in SPECIALS.items():
            part = part.replace(k, v)
        part = re.sub(r'"([^"]*)"', lambda m: "``" + m.group(1) + "''", part)
        out.append(part)
    s = "".join(out)
    for k, v in UNICODE.items():
        s = s.replace(k, v)
    s = superscripts(s)
    s = re.sub(r"\*\*(.+?)\*\*", lambda m: "\\textbf{" + m.group(1) + "}", s)
    s = re.sub(r"(?<![*\w])\*([^*]+?)\*(?![*\w])", lambda m: "\\emph{" + m.group(1) + "}", s)
    s = re.sub(r"<(https?://[^>]+)>", lambda m: "\\url{" + m.group(1) + "}", s)
    s = re.sub(r"\[([^\]@]+)\]\((https?://[^)]+)\)",
               lambda m: "\\href{" + m.group(2) + "}{" + m.group(1) + "}", s)
    s = s.replace(PIPE_MARK, "$|$").replace(STAR_MARK, "*")
    s = section_refs(s)
    s = float_refs(s)
    return cite(s)


def split_row(line):
    cells = re.split(r"(?<!\\)\|", line.strip().strip("|"))
    return [c.strip() for c in cells]


def table_lines(rows, caption=None, number=None):
    header, body = rows[0], rows[2:]
    n = len(header)
    spec = "l" * n
    inner = [r"\begin{tabular}{" + spec + "}", r"\toprule",
             " & ".join(esc(c) for c in header) + r" \\", r"\midrule"]
    for r in body:
        cells = (r + [""] * n)[:n]
        inner.append(" & ".join(esc(c) for c in cells) + r" \\")
    inner += [r"\bottomrule", r"\end{tabular}"]
    width = max(len(" | ".join(r)) for r in rows)
    if width > 70:
        inner = [r"\resizebox{\textwidth}{!}{%"] + inner + ["}"]
    lines = [r"\begin{table}[H]", r"\centering", r"\small"]
    if caption is not None:
        lines.append(r"\caption{" + esc(caption) + "}")
        lines.append(r"\label{tab:" + str(number) + "}")
    return lines + inner + [r"\end{table}"]


SPECIAL_START = ("#", "|", "```", "![", "---", "***", "___", ">")


def _is_special(line):
    s = line.strip()
    if not s or s.startswith(SPECIAL_START):
        return True
    return bool(re.match(r"^\s*([-*]\s+|\d+[.)]\s+)", line))


def unwrap(md):
    """Join hard-wrapped prose lines into one line per paragraph (tables, code, lists kept)."""
    out, buf, in_fence = [], [], False

    def flush():
        if buf:
            out.append(" ".join(buf))
            buf.clear()

    for line in md.split("\n"):
        if line.strip().startswith("```"):
            in_fence = not in_fence
            flush()
            out.append(line)
            continue
        if in_fence:
            flush()
            out.append(line)
            continue
        if re.match(r"^\s*([-*]\s+|\d+[.)]\s+)", line):
            flush()
            buf.append(line.rstrip())
        elif _is_special(line):
            flush()
            out.append(line)
        else:
            buf.append(line.strip())
    flush()
    return "\n".join(out)


FLOAT_ORDER = {"table": [], "figure": []}


def convert(md):
    md = unwrap(md)
    out, i = [], 0
    lines = md.split("\n")
    list_stack = []
    in_abstract = False

    def close_lists():
        while list_stack:
            out.append(r"\end{" + list_stack.pop() + "}")

    def next_nonblank(j):
        while j < len(lines) and not lines[j].strip():
            j += 1
        return j

    while i < len(lines):
        ln = lines[i]
        stripped = ln.strip()

        if stripped.startswith("```"):
            close_lists()
            i += 1
            body = []
            while i < len(lines) and not lines[i].strip().startswith("```"):
                body.append(lines[i])
                i += 1
            i += 1
            out += [r"\begin{quote}", r"\ttfamily\small\noindent"]
            for b in body:
                esc_b = b
                for k, v in SPECIALS.items():
                    esc_b = esc_b.replace(k, v)
                out.append(esc_b + r" \\")
            out.append(r"\end{quote}")
            continue

        if stripped.startswith("!["):
            close_lists()
            m = re.match(r"!\[([^\]]*)\]\(([^)]+)\)", stripped)
            j = next_nonblank(i + 1)
            cap = re.match(r"^\*\*Figure (\d+)\.\*\*\s*(.*)$", lines[j].strip()) if j < len(lines) else None
            if m:
                path = os.path.splitext(os.path.basename(m.group(2)))[0] + ".pdf"
                out += [r"\begin{figure}[H]", r"\centering",
                        r"\includegraphics[width=0.82\textwidth]{figures/" + path + "}"]
                if cap:
                    FLOAT_ORDER["figure"].append(int(cap.group(1)))
                    out += [r"\caption{" + esc(cap.group(2)) + "}",
                            r"\label{fig:" + cap.group(1) + "}"]
                    i = j
                out.append(r"\end{figure}")
            i += 1
            continue

        cap = re.match(r"^\*\*Table (\d+)\.\*\*\s*(.*)$", stripped)
        if cap:
            j = next_nonblank(i + 1)
            if j < len(lines) and lines[j].strip().startswith("|"):
                close_lists()
                rows = []
                k = j
                while k < len(lines) and lines[k].strip().startswith("|"):
                    rows.append(split_row(lines[k]))
                    k += 1
                FLOAT_ORDER["table"].append(int(cap.group(1)))
                out += table_lines(rows, cap.group(2), cap.group(1))
                i = k
                continue

        if stripped.startswith("|") and i + 1 < len(lines) and set(
                lines[i + 1].strip().replace("|", "").replace(" ", "")) <= {"-", ":"}:
            raise SystemExit(f"{SRC}: a table without a '**Table N.** caption' line above it "
                             f"(starts: {stripped[:60]!r}). Every table needs a numbered caption.")

        if stripped.startswith("#"):
            close_lists()
            if in_abstract:
                out.append(r"\end{abstract}")
                in_abstract = False
            level = len(stripped) - len(stripped.lstrip("#"))
            title = stripped.lstrip("#").strip()
            if title == "Abstract":
                out.append(r"\begin{abstract}")
                in_abstract = True
                i += 1
                continue
            m_app = re.match(r"^Appendix ([A-Z])\.\s*(.*)$", title)
            m_num = re.match(r"^(\d+(?:\.\d+)*)\.?\s+(.*)$", title)
            if m_app:
                out += [r"\appendix", r"\section{" + esc(m_app.group(2)) + "}",
                        r"\label{sec:" + m_app.group(1) + "}"]
            elif m_num:
                cmd = {2: "section", 3: "subsection"}.get(level, "subsubsection")
                out += ["\\" + cmd + "{" + esc(m_num.group(2)) + "}",
                        r"\label{sec:" + m_num.group(1) + "}"]
            else:
                cmd = {2: "section*", 3: "subsection*"}.get(level, "subsubsection*")
                out.append("\\" + cmd + "{" + esc(title) + "}")
            i += 1
            continue

        if stripped in ("---", "***", "___"):
            close_lists()
            i += 1
            continue

        m = re.match(r"^(\s*)[-*]\s+(.*)", ln)
        if m:
            if "itemize" not in list_stack:
                close_lists()
                out.append(r"\begin{itemize}")
                list_stack.append("itemize")
            out.append(r"\item " + esc(m.group(2)))
            i += 1
            continue

        m = re.match(r"^(\s*)\d+[.)]\s+(.*)", ln)
        if m:
            if "enumerate" not in list_stack:
                close_lists()
                out.append(r"\begin{enumerate}")
                list_stack.append("enumerate")
            out.append(r"\item " + esc(m.group(2)))
            i += 1
            continue

        if not stripped:
            close_lists()
            out.append("")
            i += 1
            continue

        out.append(esc(stripped))
        i += 1

    close_lists()
    if in_abstract:
        out.append(r"\end{abstract}")
    return "\n".join(out)


def main():
    md = open(SRC, encoding="utf-8").read()
    # HTML comments are working notes (and generated-table markers), never paper text.
    md = re.sub(r"<!--.*?-->\n?", "", md, flags=re.S)
    title = md.split("\n", 1)[0].lstrip("# ").strip()
    body = md.split("\n", 1)[1]
    # Working notes above the abstract are not part of the paper.
    body = body[body.index("## Abstract"):]

    start = body.index("## References")
    end = body.index("## Appendix A")
    main_text, appendix = body[:start], body[end:]

    os.makedirs(OUT_DIR, exist_ok=True)
    head = PREAMBLE.replace("@@TITLE@@", esc(title))
    tex = (head + "\n" + convert(main_text) + "\n\\bibliographystyle{unsrt}\n"
           "\\bibliography{references}\n\n" + convert(appendix) + "\n\n\\end{document}\n")

    declared = bib_keys(BIB)
    unknown = [k for k in USED_KEYS if k not in declared]
    uncited = [k for k in declared if k not in USED_KEYS]
    if unknown:
        raise SystemExit(f"cited but not in {BIB}: {unknown}")
    if uncited:
        raise SystemExit(f"in {BIB} but never cited: {uncited}")
    for kind, order in FLOAT_ORDER.items():
        if order != list(range(1, len(order) + 1)):
            raise SystemExit(f"{kind} numbers in the draft are not in order of appearance: {order}")
    labels = set(re.findall(r"\\label\{([^}]+)\}", tex))
    dangling = sorted(set(re.findall(r"\\ref\{([^}]+)\}", tex)) - labels)
    if dangling:
        raise SystemExit(f"references to labels that do not exist: {dangling}")

    path = os.path.join(OUT_DIR, "main.tex")
    with open(path, "w", encoding="utf-8") as f:
        f.write(tex)
    shutil.copy2(BIB, os.path.join(OUT_DIR, "references.bib"))

    figs = os.path.join(OUT_DIR, "figures")
    if os.path.isdir(figs):
        shutil.rmtree(figs)
    os.makedirs(figs)
    wanted = set(re.findall(r"figures/([\w.-]+\.pdf)", tex))
    for f in sorted(wanted):
        shutil.copy2(os.path.join(FIG_SRC, f), os.path.join(figs, f))

    bib_text = io.open(BIB, encoding="utf-8").read()
    stray = sorted({c for c in tex + bib_text if ord(c) > 0x017F})
    if stray:
        names = ", ".join(f"U+{ord(c):04X} ({unicodedata.name(c, '?')})" for c in stray)
        raise SystemExit(f"{path} contains character(s) inputenc will reject: {names}\n"
                         f"Add them to UNICODE in {__file__} and re-run.")

    # Sources only: a local compile leaves main.pdf, .aux and .bbl files in OUT_DIR.
    with zipfile.ZipFile(ZIP_OUT, "w", zipfile.ZIP_DEFLATED) as z:
        z.write(path, "main.tex")
        z.write(os.path.join(OUT_DIR, "references.bib"), "references.bib")
        for f in sorted(wanted):
            z.write(os.path.join(figs, f), f"figures/{f}")

    print(f"Wrote {path} ({os.path.getsize(path) / 1024:.0f} KB), {len(wanted)} figure(s), "
          f"{len(USED_KEYS)} references cited, {len(FLOAT_ORDER['table'])} tables, "
          f"{len(FLOAT_ORDER['figure'])} figures.")
    print(f"Wrote {ZIP_OUT} ({os.path.getsize(ZIP_OUT) / 1024:.0f} KB) -- upload this to Overleaf.")


if __name__ == "__main__":
    main()
