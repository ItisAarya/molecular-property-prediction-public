"""
scripts/make_latex.py

Convert `paper/draft.md` into an Overleaf-ready LaTeX project.

    python -m scripts.make_latex

Writes `paper/latex/main.tex` and copies the figures beside it.

WHY A CONVERTER AND NOT A HAND-WRITTEN .tex
-------------------------------------------
The Markdown draft is the source of truth: `scripts/check_paper.py` asserts its prose against
the archives, and a hand-maintained LaTeX copy would drift from it within a day. So the LaTeX
is generated, and regenerating it after every edit to the draft costs one command.

The conversion is deliberately narrow. It handles exactly the constructs this draft uses --
headings, bold, italic, inline code, fenced code, tables, bullet and numbered lists, block
images and horizontal rules -- and escapes the LaTeX specials that appear in chemistry and
statistics text. It is not a general Markdown engine, and it does not try to be: anything it
cannot parse it passes through as a paragraph, which is visible in the PDF rather than silent.

WHAT SHIPS AND WHAT IS LEFT
---------------------------
The output is a complete `article`-class project: title, author block, every section, four
figures and `references.bib`. It should compile under pdflatex in Overleaf with no edits.

The reference list is emitted twice on purpose. In the body it is a plain `enumerate`, so the
document compiles standalone with no bibliography pass. `references.bib` sits beside it with
the same 29 entries, all publisher-checked, for whenever a venue wants BibTeX -- replace the
enumerate with `\bibliographystyle{unsrt}` and `\bibliography{references}`.

Left deliberately: the venue's own class file. The preamble is venue-neutral because
`\affiliation` and `\orcid` are defined by publisher classes rather than by `article`, so the
author block uses plain line breaks that any class will accept.
"""

import os
import re
import shutil
import unicodedata
import zipfile

SRC = os.path.join("paper", "draft.md")
OUT_DIR = os.path.join("paper", "latex")
FIG_SRC = os.path.join("paper", "figures")
ZIP_OUT = os.path.join("paper", "overleaf_project.zip")

PREAMBLE = r"""% Generated by scripts/make_latex.py from paper/draft.md -- do not edit by hand.
% Regenerate with:  python -m scripts.make_latex
\documentclass[11pt,a4paper]{article}

\usepackage[utf8]{inputenc}
\usepackage[T1]{fontenc}
\usepackage{lmodern}
\usepackage[margin=2.5cm]{geometry}
\usepackage{graphicx}
\usepackage{booktabs}
\usepackage{longtable}
\usepackage{array}
\usepackage{amsmath,amssymb}
\usepackage{enumitem}
\usepackage{microtype}
\usepackage[hidelinks]{hyperref}
\usepackage{xcolor}

\definecolor{codebg}{HTML}{F4F6F8}
\newcommand{\code}[1]{\texttt{\small #1}}

\setlist{itemsep=2pt,parsep=0pt,topsep=4pt}
\renewcommand{\arraystretch}{1.15}

\title{@@TITLE@@}

% Single author. Venue-neutral on purpose: no \affiliation or \orcid macro is used, because
% those are defined by publisher classes and not by `article`. Swap this block for the
% venue's own once a template is chosen.
\author{%
  Aarya Sharma \\[2pt]
  \normalsize Department of Artificial Intelligence and Machine Learning \\
  \normalsize Universal College of Engineering, University of Mumbai, India \\[2pt]
  \normalsize \href{mailto:aarya007india@gmail.com}{aarya007india@gmail.com} \\
  \normalsize ORCID: \href{https://orcid.org/0009-0003-4765-9849}{0009-0003-4765-9849}%
}
\date{\today}

\begin{document}
\maketitle
"""

SPECIALS = {
    "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
    "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}
UNICODE = {
    "—": "---", "–": "--", "×": r"$\times$", "±": r"$\pm$", "≤": r"$\leq$",
    "≥": r"$\geq$", "≈": r"$\approx$", "→": r"$\rightarrow$", "α": r"$\alpha$",
    "§": r"\S", "'": "'", "'": "'", """: "``", """: "''", "…": r"\dots{}",
    "✓": r"\textbf{[verified]}", "⚠": r"\textbf{[unverified]}", "⊕": r"$\oplus$",
    "·": r"$\cdot$", "≡": r"$\equiv$", "Δ": r"$\Delta$", "σ": r"$\sigma$",
    # inputenc's utf8 option defines the Latin-1 range and little beyond it, so each of these
    # is a "Unicode character not set up for use with LaTeX" error rather than a bad glyph.
    # U+2212 MINUS SIGN is the one that matters: the draft uses it for every negative number.
    "−": "$-$", "′": "$'$", "∈": r"$\in$",
}

# Superscript digits and signs, collapsed as a RUN rather than one at a time: "10⁻¹⁶"
# has to become 10\textsuperscript{-16}, not three abutting \textsuperscript groups.
SUPERSCRIPTS = {
    "⁰": "0", "¹": "1", "²": "2", "³": "3", "⁴": "4", "⁵": "5",
    "⁶": "6", "⁷": "7", "⁸": "8", "⁹": "9", "⁺": "+", "⁻": "-",
}
SUPER_RUN = re.compile("[" + "".join(SUPERSCRIPTS) + "]+")


def superscripts(s):
    r"""Rewrite runs of Unicode superscripts as \textsuperscript{...}."""
    return SUPER_RUN.sub(
        lambda m: r"\textsuperscript{" + "".join(SUPERSCRIPTS[c] for c in m.group(0)) + "}", s)


def esc(text):
    """Escape LaTeX specials outside of inline code, then map the unicode this draft uses."""
    out = []
    for part in re.split(r"(`[^`]*`)", text):
        if part.startswith("`") and part.endswith("`") and len(part) > 1:
            inner = part[1:-1]
            for k, v in SPECIALS.items():
                inner = inner.replace(k, v)
            out.append(r"\code{" + inner + "}")
            continue
        for k, v in SPECIALS.items():
            part = part.replace(k, v)
        # The draft uses straight ASCII quotes; TeX renders both ends of one as a closing
        # quote unless they are spelled ``like this''. Converted in pairs, outside code
        # spans only -- a quotation mark inside `\code{...}` is usually a literal.
        part = re.sub(r'"([^"]*)"', r"``\1''", part)
        out.append(part)
    s = "".join(out)
    for k, v in UNICODE.items():
        s = s.replace(k, v)
    s = superscripts(s)
    # Emphasis, after escaping so the markers survive.
    s = re.sub(r"\*\*(.+?)\*\*", r"\\textbf{\1}", s)
    s = re.sub(r"(?<!\*)\*([^*]+?)\*(?!\*)", r"\\emph{\1}", s)
    # Bare markdown links.
    s = re.sub(r"<(https?://[^>]+)>", r"\\url{\1}", s)
    s = re.sub(r"\[([^\]]+)\]\((https?://[^)]+)\)", r"\\href{\2}{\1}", s)
    return s


def table(rows):
    """A markdown table, minus its separator row, as a booktabs tabular."""
    header, body = rows[0], rows[2:]
    n = len(header)
    spec = "l" + "l" * (n - 1)
    lines = [r"\begin{center}", r"\small",
             r"\begin{tabular}{" + spec + "}", r"\toprule",
             " & ".join(esc(c) for c in header) + r" \\", r"\midrule"]
    for r in body:
        cells = (r + [""] * n)[:n]
        lines.append(" & ".join(esc(c) for c in cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{center}"]
    return lines


def split_row(line):
    return [c.strip() for c in line.strip().strip("|").split("|")]


SPECIAL_START = ("#", "|", "```", "![", "---", "***", "___", ">")


def _is_special(line):
    s = line.strip()
    if not s or s.startswith(SPECIAL_START):
        return True
    return bool(re.match(r"^\s*([-*]\s+|\d+[.)]\s+)", line))


def unwrap(md):
    """
    Join hard-wrapped prose lines into one line per paragraph.

    The draft is wrapped at ~95 characters, which means a `**bold span**` routinely straddles
    a line break. `esc()` works a line at a time, so those spans survived into the LaTeX as
    literal asterisks. Reflowing first is the fix, and LaTeX does not care about the wrapping
    it removes. Fenced code, tables, headings, lists and images are left exactly as they are.
    """
    out, buf, in_fence = [], [], False

    def flush():
        if buf:
            out.append(" ".join(buf))
            buf.clear()

    for line in md.split("\n"):
        if line.strip().startswith("```"):
            in_fence = not in_fence
            flush()
            out.append(line)
            continue
        if in_fence:
            flush()
            out.append(line)
            continue

        is_item = bool(re.match(r"^\s*([-*]\s+|\d+[.)]\s+)", line))
        if is_item:
            # A list item opens its own buffer, so its wrapped continuation lines join it
            # rather than becoming stray paragraphs -- which is where the last two bold
            # spans were surviving as literal asterisks.
            flush()
            buf.append(line.rstrip())
        elif _is_special(line):
            flush()
            out.append(line)
        else:
            buf.append(line.strip())
    flush()
    return "\n".join(out)


def convert(md):
    md = unwrap(md)
    out, i = [], 0
    lines = md.split("\n")
    list_stack = []

    def close_lists():
        while list_stack:
            out.append(r"\end{" + list_stack.pop() + "}")

    while i < len(lines):
        ln = lines[i]
        stripped = ln.strip()

        if stripped.startswith("```"):
            close_lists()
            i += 1
            body = []
            while i < len(lines) and not lines[i].strip().startswith("```"):
                body.append(lines[i])
                i += 1
            i += 1
            out += [r"\begin{quote}", r"\ttfamily\small\noindent"]
            for b in body:
                esc_b = b
                for k, v in SPECIALS.items():
                    esc_b = esc_b.replace(k, v)
                out.append(esc_b + r" \\")
            out.append(r"\end{quote}")
            continue

        if stripped.startswith("!["):
            close_lists()
            m = re.match(r"!\[([^\]]*)\]\(([^)]+)\)", stripped)
            if m:
                path = os.path.basename(m.group(2))
                out += [r"\begin{center}",
                        r"\includegraphics[width=0.86\textwidth]{figures/" + path + "}",
                        r"\end{center}"]
            i += 1
            continue

        if stripped.startswith("|") and i + 1 < len(lines) and set(
                lines[i + 1].strip().replace("|", "").replace(" ", "")) <= {"-", ":"}:
            close_lists()
            rows = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                rows.append(split_row(lines[i]))
                i += 1
            out += table(rows)
            continue

        if stripped.startswith("#"):
            close_lists()
            level = len(stripped) - len(stripped.lstrip("#"))
            title = stripped.lstrip("#").strip()
            title = re.sub(r"^\d+(\.\d+)*\.?\s*", "", title)
            cmd = {1: "section", 2: "section", 3: "subsection", 4: "subsubsection"}.get(
                level, "paragraph")
            out.append("\\" + cmd + "{" + esc(title) + "}")
            i += 1
            continue

        if stripped in ("---", "***", "___"):
            close_lists()
            i += 1
            continue

        m = re.match(r"^(\s*)[-*]\s+(.*)", ln)
        if m:
            if "itemize" not in list_stack:
                close_lists()
                out.append(r"\begin{itemize}")
                list_stack.append("itemize")
            out.append(r"\item " + esc(m.group(2)))
            i += 1
            continue

        m = re.match(r"^(\s*)\d+[.)]\s+(.*)", ln)
        if m:
            if "enumerate" not in list_stack:
                close_lists()
                out.append(r"\begin{enumerate}")
                list_stack.append("enumerate")
            out.append(r"\item " + esc(m.group(2)))
            i += 1
            continue

        if not stripped:
            close_lists()
            out.append("")
            i += 1
            continue

        if list_stack:
            out.append(esc(stripped))
        else:
            out.append(esc(stripped))
        i += 1

    close_lists()
    return "\n".join(out)


def main():
    md = open(SRC, encoding="utf-8").read()

    title = md.split("\n", 1)[0].lstrip("# ").strip()
    body = md.split("\n", 1)[1]
    # Drop the draft-status banner; it is a working note, not part of the paper.
    body = re.sub(r"\*\*Draft — Phase 5.*?make_figures`\.\n", "", body, flags=re.S)

    os.makedirs(OUT_DIR, exist_ok=True)
    # Explicit replacement rather than %-formatting: the preamble is full of LaTeX comments
    # and escaped percent signs, and %-formatting chokes on every one of them.
    head = PREAMBLE.replace("@@TITLE@@", esc(title))
    tex = head + "\n" + convert(body) + "\n\n\\end{document}\n"

    path = os.path.join(OUT_DIR, "main.tex")
    with open(path, "w", encoding="utf-8") as f:
        f.write(tex)

    # The bibliography travels with the project so Overleaf can compile it directly.
    bib = os.path.join("paper", "references.bib")
    if os.path.exists(bib):
        shutil.copy2(bib, os.path.join(OUT_DIR, "references.bib"))

    figs = os.path.join(OUT_DIR, "figures")
    os.makedirs(figs, exist_ok=True)
    n = 0
    if os.path.isdir(FIG_SRC):
        for f in sorted(os.listdir(FIG_SRC)):
            if f.endswith(".pdf"):
                shutil.copy2(os.path.join(FIG_SRC, f), os.path.join(figs, f))
                n += 1

    # Refuse to ship a .tex that pdflatex will reject.
    #
    # `\usepackage[utf8]{inputenc}` defines the Latin-1 and Latin Extended-A ranges and
    # almost nothing above them, so a character like U+2212 MINUS SIGN is not a bad glyph in
    # the PDF -- it is "Unicode character not set up for use with LaTeX", a hard error, and
    # the first thing anyone uploading this to Overleaf would hit. The draft had twenty-one
    # minus signs, five superscript minuses, four primes and an element-of before this check
    # existed. Add the character to UNICODE or SUPERSCRIPTS rather than deleting it from the
    # draft: the draft is the source of truth and reads better with real typography.
    stray = sorted({c for c in tex if ord(c) > 0x017F})
    if stray:
        names = ", ".join(f"U+{ord(c):04X} ({unicodedata.name(c, '?')})" for c in stray)
        raise SystemExit(
            f"{path} contains {len(stray)} character(s) inputenc will reject: {names}\n"
            f"Add them to UNICODE or SUPERSCRIPTS in {__file__} and re-run.")

    # Build the upload bundle here rather than leaving it as a manual step. Zipping by hand
    # is where the figures get left behind: `main.tex` alone compiles with four missing-image
    # errors, which reads like a broken document rather than an incomplete upload.
    with zipfile.ZipFile(ZIP_OUT, "w", zipfile.ZIP_DEFLATED) as z:
        for folder, _, names in os.walk(OUT_DIR):
            for name in sorted(names):
                full = os.path.join(folder, name)
                z.write(full, os.path.relpath(full, OUT_DIR))

    size = os.path.getsize(path) / 1024
    print(f"Wrote {path} ({size:.0f} KB) and {n} figure(s) into {figs}/")
    print(f"Wrote {ZIP_OUT} ({os.path.getsize(ZIP_OUT) / 1024:.0f} KB) -- upload this.")
    print("\nFor Overleaf: New Project -> Upload Project -> paper/overleaf_project.zip.")
    print("It should compile under pdflatex as-is -- title, author block, figures and all.")
    print("references.bib ships alongside for whenever a venue wants BibTeX; the body's")
    print("enumerate list means the document also compiles without a bibliography pass.")
    print("Left for the venue: its own class file, if it has one.")


if __name__ == "__main__":
    main()
